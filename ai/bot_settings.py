"""Validate portable Outlands AI presets and generate a bounded native catalog."""
import argparse
import json
import math
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
SOURCE=Path(__file__).with_name('bot_settings.json')
NATIVE=ROOT/'storage/t6/scripts/mp/outlands_human_catalog.gsc'
TIERS=('developing','regular','experienced','standout')
COMBAT=('difficulty','converge_ms','correction_rate','aim_error','smooth_ms')


def bounded(value,low,high,integer=True):
    return type(value) in ((int,) if integer else (int,float)) and math.isfinite(value) and low<=value<=high


def unique_pairs(pairs):
    result={}
    for k,v in pairs:
        if k in result:raise ValueError('Duplicate settings key')
        result[k]=v
    return result


def load_settings(path=SOURCE):
    path=Path(path)
    if path.is_symlink() or path.stat().st_size>131072:raise ValueError('Invalid settings source')
    data=json.loads(path.read_text(),object_pairs_hook=unique_pairs,parse_constant=lambda _: (_ for _ in ()).throw(ValueError('Nonfinite setting')))
    if not isinstance(data,dict) or set(data)!={'schema_version','default_preset','presets'} or type(data['schema_version']) is not int or data['schema_version']!=1:
        raise ValueError('Unknown settings schema')
    presets=data['presets']
    if not isinstance(presets,dict) or not 1<=len(presets)<=16 or not isinstance(data['default_preset'],str) or data['default_preset'] not in presets:
        raise ValueError('Invalid preset collection')
    for name,p in presets.items():
        if not re.fullmatch(r'[a-z][a-z0-9_]{0,23}',name) or not isinstance(p,dict) or set(p)!={'engine','guard','combat'}:raise ValueError('Invalid preset')
        e=p['engine'];g=p['guard'];c=p['combat']
        if not isinstance(e,dict) or set(e)!={'yaw_speed','reaction_min_ms','reaction_max_ms'} or not bounded(e['yaw_speed'],0.5,1.2,False) or not bounded(e['reaction_min_ms'],300,1600) or not bounded(e['reaction_max_ms'],300,2000) or e['reaction_max_ms']<e['reaction_min_ms']:
            raise ValueError('Unsafe native engine limits')
        if not isinstance(g,dict) or set(g)!={'hold_min_ms','hold_max_ms','travel_timeout_ms','min_step_units'} or not bounded(g['hold_min_ms'],1500,12000) or not bounded(g['hold_max_ms'],1500,12000) or g['hold_max_ms']<g['hold_min_ms'] or not bounded(g['travel_timeout_ms'],8000,30000) or not bounded(g['min_step_units'],64,256):
            raise ValueError('Unsafe guard limits')
        if not isinstance(c,dict) or set(c)!=set(TIERS):raise ValueError('Missing combat tiers')
        for tier,t in c.items():
            if not isinstance(t,dict) or set(t)!=set(COMBAT) or t['difficulty'] not in ('easy','normal','hard') or not bounded(t['converge_ms'],1000,4500) or not bounded(t['correction_rate'],1,7) or not bounded(t['aim_error'],12,40) or not bounded(t['smooth_ms'],150,600):
                raise ValueError('Unsafe native combat limits')
    return data


def selected_preset(name='mixed',path=SOURCE):
    data=load_settings(path)
    if not isinstance(name,str) or name not in data['presets']:raise ValueError('Unknown preset')
    return data['presets'][name]


def generated_catalog(data):
    def values(items):return ', '.join(json.dumps(x,allow_nan=False) for x in items)
    lines=['// Generated by ai/bot_settings.py; original bounded Outlands settings.','preset_name( name )','{']
    for name in sorted(data['presets']):lines.append(f'    if ( name == "{name}" ) return "{name}";')
    lines.extend([f'    return "{data["default_preset"]}";','}',''])
    for function,group,keys in [('engine','engine',('yaw_speed','reaction_min_ms','reaction_max_ms')),('guard','guard',('hold_min_ms','hold_max_ms','travel_timeout_ms','min_step_units'))]:
        lines.extend([f'{function}( name )','{','    name = preset_name( name );'])
        for name,p in sorted(data['presets'].items()):lines.append(f'    if ( name == "{name}" ) return array( {values(p[group][k] for k in keys)} );')
        lines.extend(['    return undefined;','}',''])
    lines.extend(['combat( tier, name )','{','    name = preset_name( name );'])
    for name,p in sorted(data['presets'].items()):
        lines.extend([f'    if ( name == "{name}" )','    {'])
        for tier in TIERS:lines.append(f'        if ( tier == "{tier}" ) return array( {values(p["combat"][tier][k] for k in COMBAT)} );')
        lines.append('    }')
    lines.extend(['    return undefined;','}',''])
    return '\n'.join(lines)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,default=SOURCE)
    mode=parser.add_mutually_exclusive_group()
    mode.add_argument('--generate',action='store_true')
    mode.add_argument('--export-preset')
    args=parser.parse_args()
    try:
        data=load_settings(args.source);native=generated_catalog(data)
        if args.export_preset:
            if args.export_preset not in data['presets']:raise ValueError('Unknown preset')
            print(json.dumps({'schema_version':1,'default_preset':args.export_preset,'presets':{args.export_preset:data['presets'][args.export_preset]}},indent=2));return 0
        if args.generate:NATIVE.write_text(native)
        elif NATIVE.read_text()!=native:raise ValueError('Native settings catalog differs; regenerate and test before building')
        print('PASS: bounded presets '+', '.join(sorted(data['presets'])))
        return 0
    except (OSError,ValueError,TypeError):
        print('Settings validation failed; check schema, bounds and generated catalog.')
        return 1


if __name__=='__main__':raise SystemExit(main())
